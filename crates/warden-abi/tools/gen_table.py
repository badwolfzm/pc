#!/usr/bin/env python3
"""Generate src/linux_x86_64.rs from the kernel UAPI header (unistd_64.h)."""
import re, sys
hdr = sys.argv[1]
rows = []
for line in open(hdr):
    m = re.match(r'#define __NR_(\w+)\s+(\d+)', line)
    if m:
        rows.append((m.group(1), int(m.group(2))))
rows.sort(key=lambda r: r[1])
out = ["// @generated by tools/gen_table.py from linux UAPI asm/unistd_64.h. Do not edit.",
       "/// (name, number) for every x86-64 Linux syscall known to the UAPI header.",
       "pub const SYSCALLS: &[(&str, u32)] = &["]
out += [f'    ("{n}", {nr}),' for n, nr in rows]
out.append("];")
print("\n".join(out))
